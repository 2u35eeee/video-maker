"""Narration: one TTS call per script line, then a timeline both picture and sound import.

    uv run engine/tts.py projects/kp-001-birthday [--voice serena] [--tempo 1.1] [--force]

Reads  projects/<name>/script.json:
    { "voice": "serena", "tempo": 1.1, "instruct": "...", "lead": 0.3, "tail": 1.2,
      "lines": [ { "id": "q", "say": "spoken text", "sub": "on-screen text with 【highlight】",
                   "instruct": "optional per-line style", "pause": 0.25 } ] }
Writes out/<name>/vo.wav (44.1 kHz mono) and projects/<name>/vo.js (line timings).
Each line is cached by (text, voice, style, tempo), so editing one line only regenerates that line.
"""

import argparse
import hashlib
import json
import subprocess
import sys
import time
import wave
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
MODEL = "mlx-community/Qwen3-TTS-12Hz-1.7B-CustomVoice-8bit"
SR = 44100


def wav_seconds(path: Path) -> float:
    with wave.open(str(path)) as w:
        return w.getnframes() / w.getframerate()


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("project")
    ap.add_argument("--voice")
    ap.add_argument("--tempo", type=float)
    ap.add_argument("--force", action="store_true", help="ignore the cache")
    args = ap.parse_args()

    proj = Path(args.project).resolve()
    name = proj.name
    script = json.loads((proj / "script.json").read_text())
    voice = args.voice or script.get("voice", "serena")
    tempo = args.tempo or script.get("tempo", 1.0)
    base_style = script.get("instruct", "")
    lead, tail = script.get("lead", 0.3), script.get("tail", 1.2)

    out = ROOT / "out" / name
    cache = out / "vo"
    cache.mkdir(parents=True, exist_ok=True)

    model = None
    clips = []
    for line in script["lines"]:
        style = "，".join(s for s in (base_style, line.get("instruct", "")) if s)
        key = hashlib.sha1(json.dumps([line["say"], voice, style, tempo, MODEL]).encode()).hexdigest()[:12]
        clip = cache / f"{line['id']}-{key}.wav"
        if args.force or not clip.exists():
            if model is None:
                from mlx_audio.tts import load

                t0 = time.time()
                model = load(MODEL)
                print(f"model loaded {time.time() - t0:.1f}s", file=sys.stderr)
            t0 = time.time()
            parts = list(model.generate(text=line["say"], voice=voice, instruct=style or None))
            audio = np.concatenate([np.array(p.audio, dtype=np.float32) for p in parts])
            raw = clip.with_suffix(".raw.f32")
            audio.tofile(raw)
            # trim edge silence, apply tempo (pitch-preserving), resample to 44.1 kHz s16
            filters = "silenceremove=start_periods=1:start_threshold=-45dB,areverse,silenceremove=start_periods=1:start_threshold=-45dB,areverse"
            if tempo != 1.0:
                filters += f",atempo={tempo}"
            subprocess.run(
                ["ffmpeg", "-loglevel", "error", "-y", "-f", "f32le", "-ar", str(parts[0].sample_rate), "-ac", "1",
                 "-i", str(raw), "-af", filters, "-ar", str(SR), "-ac", "1", "-sample_fmt", "s16", str(clip)],
                check=True,
            )
            raw.unlink()
            print(f"  {line['id']:<10} {wav_seconds(clip):5.2f}s  ({time.time() - t0:.1f}s)  {line['say']}", file=sys.stderr)
        clips.append((line, clip))

    # Lay the clips on one timeline.
    t = lead
    timeline = []
    for line, clip in clips:
        d = wav_seconds(clip)
        timeline.append({"id": line["id"], "say": line["say"], "sub": line.get("sub", line["say"]),
                         "start": round(t, 3), "end": round(t + d, 3), "clip": clip.name})
        t += d + line.get("pause", 0.25)
    duration = round(timeline[-1]["end"] + tail, 3)

    total = np.zeros(int(duration * SR) + 1, dtype=np.int16)
    for (line, clip), seg in zip(clips, timeline):
        with wave.open(str(clip)) as w:
            pcm = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16)
        s = int(seg["start"] * SR)
        total[s : s + len(pcm)] = pcm[: len(total) - s]
    with wave.open(str(out / "vo.wav"), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(total.tobytes())

    js = (
        "// Generated by engine/tts.py — do not edit. Narration timings in seconds.\n"
        f"export const VOICE = {json.dumps(voice)};\n"
        f"export const DURATION = {duration};\n"
        f"export const VO = {json.dumps(timeline, ensure_ascii=False, indent=2)};\n"
        "export const cue = (id) => VO.find((l) => l.id === id);\n"
    )
    (proj / "vo.js").write_text(js)
    print(f"vo.wav {duration:.2f}s, {len(timeline)} lines, voice={voice}, tempo={tempo}")


if __name__ == "__main__":
    main()
